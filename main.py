import io
import json
import os
import re
import time
import uuid
from contextlib import asynccontextmanager
import gc
import threading
 
import numpy as np
import tensorflow as tf
from fastapi import FastAPI, File, Form, HTTPException, Request, UploadFile
from fastapi.responses import HTMLResponse
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates
from PIL import Image
 
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
UPLOAD_DIR = os.path.join(BASE_DIR, "static", "uploads")
os.makedirs(UPLOAD_DIR, exist_ok=True)                       # M3
 
IMG_SIZE = (224, 224)
MAX_UPLOAD_BYTES = 5 * 1024 * 1024                           # 5 MB
ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png"}
SAFE_FILENAME = re.compile(r"^[0-9a-f]{32}\.(jpg|jpeg|png)$")  # M4
 
MODEL_FILES = {
    "mobilenetv2": "dog_breed_classifier_mobilenetv2.h5",
    "inceptionv3": "dog_breed_classifier_inceptionv3.h5",
    "resnet50v2": "dog_breed_classifier_resnet50v2.h5",
}
 
# M2: generated by the notebook (see N1); must contain exactly 133 names
with open(os.path.join(BASE_DIR, "class_names.json"), encoding="utf-8") as f:
    CLASS_NAMES = json.load(f)
 
models = {}
model_lock = threading.Lock()

@asynccontextmanager
async def lifespan(app: FastAPI):
    print("Application started. Models will load on demand.")
    yield
    models.clear()
 
 
app = FastAPI(title="Dog Breed Classification", lifespan=lifespan)
app.mount("/static", StaticFiles(directory=os.path.join(BASE_DIR, "static")), name="static")
templates = Jinja2Templates(directory=os.path.join(BASE_DIR, "templates"))
 
def cleanup_old_uploads(max_age_seconds: int = 3600):         # M10
    now = time.time()
    for name in os.listdir(UPLOAD_DIR):
        path = os.path.join(UPLOAD_DIR, name)
        if os.path.isfile(path) and now - os.path.getmtime(path) > max_age_seconds:
            os.remove(path)
 
 
def predict_breed(model_name: str, image_path: str):
    with model_lock:
        if model_name not in models:
            # Release the previously loaded model
            models.clear()
            gc.collect()
            tf.keras.backend.clear_session()

            # Load only the selected model
            model_path = os.path.join(
                BASE_DIR, MODEL_FILES[model_name]
            )
            models[model_name] = tf.keras.models.load_model(
                model_path, compile=False
            )

        model = models[model_name]

        img = tf.keras.utils.load_img(
            image_path, target_size=IMG_SIZE
        )
        img_array = tf.keras.utils.img_to_array(img) / 255.0
        img_array = np.expand_dims(img_array, axis=0)

        probs = model.predict(img_array, verbose=0)[0]
        idx = int(np.argmax(probs))

        return (
            CLASS_NAMES[idx].replace("_", " ").title(),
            float(probs[idx])
        )
 
@app.get("/", response_class=HTMLResponse)
async def home(request: Request):
    return templates.TemplateResponse(request, "index.html")
 
 
@app.post("/upload", response_class=HTMLResponse)
async def handle_upload(request: Request, file: UploadFile = File(...), model_name: str = Form(...)):
    if model_name not in MODEL_FILES:                         # M6
        raise HTTPException(status_code=400, detail="Unknown model selected.")
 
    ext = os.path.splitext(file.filename or "")[1].lower()    # M5
    if ext not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail="Only .jpg, .jpeg and .png images are allowed.")
 
    data = await file.read(MAX_UPLOAD_BYTES + 1)
    if len(data) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="Image is larger than 5 MB.")
    try:
        Image.open(io.BytesIO(data)).verify()
    except Exception:
        raise HTTPException(status_code=400, detail="File is not a valid image.")
 
    cleanup_old_uploads()
    filename = f"{uuid.uuid4().hex}{ext}"                     # M4: never use the client's filename
    with open(os.path.join(UPLOAD_DIR, filename), "wb") as buffer:
        buffer.write(data)
 
    return templates.TemplateResponse(
        request, "confirm.html", {"filename": filename, "model_name": model_name}
    )
 
 
@app.post("/predict", response_class=HTMLResponse)
def handle_predict(request: Request, filename: str = Form(...), model_name: str = Form(...)):
    # plain "def" (not "async def") -> FastAPI runs it in a worker thread (M8)
    if model_name not in MODEL_FILES:
        raise HTTPException(status_code=400, detail="Unknown model selected.")
    if not SAFE_FILENAME.match(filename):                     # M4
        raise HTTPException(status_code=400, detail="Invalid filename.")
    image_path = os.path.join(UPLOAD_DIR, filename)
    if not os.path.isfile(image_path):
        raise HTTPException(status_code=404, detail="Image expired. Please upload again.")
 
    breed, confidence = predict_breed(model_name, image_path)
    return templates.TemplateResponse(
        request, "result.html",
        {"filename": filename, "prediction": breed, "confidence": round(confidence * 100, 1)},
    )
 
 
@app.get("/health")
async def health():
    return {"status": "ok", "models_loaded": list(models.keys())}
